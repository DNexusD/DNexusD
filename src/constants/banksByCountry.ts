export function getBanksForCountry(country?: string): string[] {
  const cleanCountry = (country || '').trim();
  if (!cleanCountry) return [];

  if (BANKS_BY_COUNTRY[cleanCountry]) {
    return BANKS_BY_COUNTRY[cleanCountry];
  }

  // Fuzzy match for minor spelling differences (e.g. عمان vs عُمان, السعودية)
  const normalized = cleanCountry.replace(/[أإآ]/g, 'ا').replace(/ُ/g, '');
  for (const [key, banks] of Object.entries(BANKS_BY_COUNTRY)) {
    const normKey = key.replace(/[أإآ]/g, 'ا').replace(/ُ/g, '');
    if (normKey === normalized || normKey.includes(normalized) || normalized.includes(normKey)) {
      return banks;
    }
  }

  return [];
}
